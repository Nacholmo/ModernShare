"""Export fixed edits only; compiled hooks, theme, boot art and English are rebuilt."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT/'tools'),str(ROOT/'mods/fullscreen/src')]
import kodakfw
import build_fullscreen as boot

def sha(b):return hashlib.sha256(b).hexdigest()

def export(stock,target,output):
    original=stock.read_bytes();final=target.read_bytes()
    if len(original)!=len(final) or kodakfw.check(original) or kodakfw.check(final):raise ValueError('invalid firmware inputs')
    if output.exists():raise FileExistsError(output)
    assembly=json.loads((ROOT/'src/release/assembly.json').read_text())
    off=lambda a:kodakfw.ram_to_file(original,a)
    excluded=set()
    def omit(at,n):excluded.update(range(at,at+n))
    for unit in assembly:
        for s in unit['segments']:
            at=off(unit['origin']+s['offset']);n=s['length'];s['sha256']=sha(final[at:at+n]);omit(at,n)
    for r in kodakfw.records(original):
        if r['type'] in (0,1):omit(0x10+r['idx']*16+12,4)
    omit(0x1f4,8);omit(off(0x1241a0),1536)
    # Both complete palettes and the per-widget theme colours are generated by make_theme.py.
    from importlib.util import spec_from_file_location,module_from_spec
    spec=spec_from_file_location('theme',ROOT/'mods/theme/src/make_theme.py');theme=module_from_spec(spec);spec.loader.exec_module(theme)
    for at in theme.TABLES:omit(at,1024)
    for at in theme.UI_COLOURS:omit(off(at),4)
    # Image pixels are supplied as editable PNGs, never a compiled graphics dump.
    from PIL import Image
    legacy=Image.open(ROOT/'assets/legacy-banner-indexed.png')
    omit(off(0x1d8127),len(boot.m.encode(legacy.tobytes())))
    omit(boot.REC3_FILE+0x6ba00,boot.LANG_MAX)
    for i in range(5):omit(off(0x1254b0+20*i),4)
    copies=[dict(source_offset=off(0x1cd328),destination_offset=off(0x125520),length=224,reason='Relocate original first graphic block from local stock image')]
    for c in copies:
        assert original[c['source_offset']:c['source_offset']+c['length']]==final[c['destination_offset']:c['destination_offset']+c['length']]
        omit(c['destination_offset'],c['length'])
    # Store only changed contiguous bytes. Do not carry unchanged vendor instruction/data slices.
    groups=[]
    for at,(a,b) in enumerate(zip(original,final)):
        if a==b or at in excluded:continue
        if groups and at==groups[-1][-1]+1:groups[-1].append(at)
        else:groups.append([at])
    edits=[]
    for group in groups:
        at,n=group[0],len(group)
        edits.append(dict(file_offset=at,length=n,stock_sha256=sha(original[at:at+n]),value=final[at:at+n].hex()))
    result=dict(format=1,version='ModernShare 0.8',stock_sha256=sha(original),firmware_sha256=sha(final),
                description='Fixed reverse-engineered edits and generated film/menu data; source-compiled and vendor-copy areas excluded',
                assembly=assembly,stock_copies=copies,edits=edits)
    output.parent.mkdir(parents=True,exist_ok=True)
    with output.open('x') as f:f.write(json.dumps(result,indent=2)+'\n')
    print(f'{len(edits)} edits, {sum(e["length"] for e in edits)} changed bytes; no firmware image included')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--stock',type=Path,required=True);p.add_argument('--target',type=Path,required=True);p.add_argument('--out',type=Path,required=True)
    a=p.parse_args();export(a.stock,a.target,a.out)
